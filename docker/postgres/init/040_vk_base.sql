-- VK Base: схема учебной социальной сети в PostgreSQL
-- Запуск через psql: psql -U postgres -f 040_vk_base.sql
-- Если база уже создана, пропустите CREATE DATABASE и \connect.

CREATE DATABASE sqltutor_vk_base OWNER postgres;
\connect sqltutor_vk_base

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE users (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username VARCHAR(40) NOT NULL UNIQUE,
                       email VARCHAR(255) NOT NULL UNIQUE,
                       first_name VARCHAR(80) NOT NULL,
                       last_name VARCHAR(80) NOT NULL,
                       birth_date DATE,
                       city VARCHAR(100),
                       bio TEXT,
                       is_verified BOOLEAN NOT NULL DEFAULT FALSE,
                       is_private BOOLEAN NOT NULL DEFAULT FALSE,
                       status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
                           CHECK (status IN ('ACTIVE', 'DEACTIVATED', 'BANNED')),
                       created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                       last_seen_at TIMESTAMPTZ
);

CREATE TABLE communities (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             name VARCHAR(160) NOT NULL,
                             slug VARCHAR(180) NOT NULL UNIQUE,
                             description TEXT,
                             category VARCHAR(80) NOT NULL,
                             city VARCHAR(100),
                             is_verified BOOLEAN NOT NULL DEFAULT FALSE,
                             created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
                             created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE community_members (
                                   community_id BIGINT NOT NULL REFERENCES communities(id) ON DELETE CASCADE,
                                   user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                                   role VARCHAR(20) NOT NULL DEFAULT 'MEMBER'
                                       CHECK (role IN ('OWNER', 'ADMIN', 'MODERATOR', 'MEMBER')),
                                   joined_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                                   notifications_enabled BOOLEAN NOT NULL DEFAULT TRUE,
                                   PRIMARY KEY (community_id, user_id)
);

CREATE TABLE friendships (
                             requester_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                             addressee_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                             status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
                                 CHECK (status IN ('PENDING', 'ACCEPTED', 'DECLINED', 'BLOCKED')),
                             requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                             accepted_at TIMESTAMPTZ,
                             PRIMARY KEY (requester_id, addressee_id),
                             CHECK (requester_id <> addressee_id),
                             CHECK ((status = 'ACCEPTED' AND accepted_at IS NOT NULL) OR status <> 'ACCEPTED')
);

CREATE TABLE posts (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                       community_id BIGINT REFERENCES communities(id) ON DELETE CASCADE,
                       text TEXT NOT NULL,
                       post_type VARCHAR(20) NOT NULL DEFAULT 'TEXT'
                           CHECK (post_type IN ('TEXT', 'PHOTO', 'VIDEO', 'LINK', 'POLL')),
                       visibility VARCHAR(20) NOT NULL DEFAULT 'PUBLIC'
                           CHECK (visibility IN ('PUBLIC', 'FRIENDS', 'COMMUNITY', 'PRIVATE')),
                       is_pinned BOOLEAN NOT NULL DEFAULT FALSE,
                       created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                       edited_at TIMESTAMPTZ,
                       deleted_at TIMESTAMPTZ,
                       CHECK (edited_at IS NULL OR edited_at >= created_at),
                       CHECK (deleted_at IS NULL OR deleted_at >= created_at)
);

CREATE TABLE post_views (
                            post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
                            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                            viewed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                            duration_seconds INTEGER NOT NULL DEFAULT 0 CHECK (duration_seconds >= 0),
                            PRIMARY KEY (post_id, user_id)
);

CREATE TABLE reactions (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
                           user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
                           reaction_type VARCHAR(20) NOT NULL DEFAULT 'LIKE'
                               CHECK (reaction_type IN ('LIKE', 'LOVE', 'HAHA', 'WOW', 'SAD', 'ANGRY')),
                           created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                           UNIQUE (post_id, user_id)
);

